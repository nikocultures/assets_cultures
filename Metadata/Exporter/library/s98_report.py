"""Stage 98: final report computed from the catalogs (no hand-entered numbers)."""
import csv, collections
from common import *


def rows(p):
    with open(ROOT / p, encoding='utf-8-sig') as f:
        return list(csv.DictReader(f))


X = rows('Catalogs/asset_cross_reference.csv')
cen = read(ROOT / 'Unknown/census_summary.json')
cat = read(ROOT / 'Catalogs/catalog_summary.json')
val = read(ROOT / 'Metadata/Evidence/library/browser_validation.json')
tests = read(ROOT / 'Metadata/Evidence/library/focused_tests.json')
hashes = read(ROOT / 'Metadata/Evidence/library/source_hashes_after.json') if (ROOT / 'Metadata/Evidence/library/source_hashes_after.json').exists() else {}
TN = {'1': 'Vikings', '2': 'Franks', '3': 'Byzantines', '4': 'Saracens (Arabs)', '5': 'Weresnakes', '6': 'Werewolves', '7': 'Egypt'}
houses = rows('Catalogs/houses.csv')
hb = collections.Counter(TN[r['TRIBE']] for r in houses)
hdefs = collections.Counter(TN[r['TRIBE']] for r in {(r['TRIBE'], r['GFX_ID']): r for r in houses}.values())
hst = collections.Counter((TN[r['TRIBE']], r['STATUS']) for r in houses)
hum = rows('Catalogs/humans.csv')
ha = rows('Catalogs/human_job_atomic_animation.csv')
veh = rows('Catalogs/vehicles.csv')
ani = rows('Catalogs/animals.csv')
img = rows('Catalogs/images.csv')
aud = rows('Catalogs/audio.csv')
unk = rows('Catalogs/unknown_assets.csv')
ui = rows('Catalogs/ui_sprites.csv')
fx = rows('Catalogs/effects.csv')
fonts = rows('Catalogs/fonts.csv')
st = collections.Counter(r['STATUS'] for r in X)
L = []
w = L.append
w('# Cultures original asset library: final report\n')
w('Generated by `Metadata/Exporter/library/s98_report.py` from the catalogs; every figure below is computed, not typed.\n')
w('| Item | Value |\n|---|---|')
for k, v in [('Asset root', r'E:\assets cultures'), ('Main index', r'E:\assets cultures\index.html'),
             ('Total source files (DataX + original, hashed)', hashes.get('filesChecked', 130)), ('Total archive entries', cat['archiveEntries']),
             ('Archive entries unaccounted', len(cat['archiveUnaccounted'])), ('Total CIF', sum(1 for r in X if r['CATEGORY'] == 'Native definitions')),
             ('Total BMD', cen['bmdLibraries']), ('Total BOB descriptors (frames)', cen['frameDescriptors']), ('Total non-empty frames', cen['nonemptyFrames']),
             ('Unsupported-kind frames (test_house.bmd, kind 3)', cen['unsupportedKindFrames']), ('Mapped frames', cen['mappedFrames']),
             ('Named-sequence unbound frames', cen['namedSequenceUnbound']), ('True unknown (unreferenced) frames', cen['trueUnknownUnreferenced']),
             ('UI sprites with unknown palette', cen['classes'].get('UNKNOWN_PALETTE', 0)),
             ('PCX', sum(r['FORMAT'] == 'PCX' for r in img)), ('BMP (archive + DataX Pictures)', sum(r['FORMAT'] == 'BMP' for r in img)),
             ('PSD', sum(r['FORMAT'] == 'PSD' for r in img)), ('Cursors', sum(r['FORMAT'] == 'CUR' for r in img)),
             ('Fonts (FNT entries / unique)', f"{len(fonts)} / {sum(r['STATUS'] == 'DECODED' for r in fonts)}"),
             ('WAV', sum(1 for r in aud if r['ENTRY'].lower().endswith('.wav'))), ('DirectMusic', sum(1 for r in aud if r['ARCHIVE'] == 'loose DataX file')),
             ('FMV', sum(1 for r in X if r['CATEGORY'] == 'FMV')), ('Native documents (HLT/DAT/TXT)', sum(1 for r in X if r['CATEGORY'] == 'Native documents'))]:
    w(f'| {k} | {v} |')
w('\n## Buildings by tribe\n\n| Tribe | Definitions | Levels | Status per level |\n|---|---|---|---|')
for t in sorted(hb):
    w(f"| {t} | {hdefs[t]} | {hb[t]} | {', '.join(f'{s} {n}' for (tt, s), n in sorted(hst.items()) if tt == t)} |")
w('\n## Humans by tribe\n\n| Tribe | Jobs with graphics | Animation x binding rows | Rendered | Partial (missing native frames) | Variant incompatible | Timeline (mode 2) |\n|---|---|---|---|---|---|---|')
for t in sorted(TN):
    hr = [r for r in ha if r['TRIBE_ID'] == t]
    c = collections.Counter(r['RENDER_STATUS'].split(':')[0].split(' (')[0] for r in hr)
    w(f"| {TN[t]} | {sum(r['TRIBE_ID'] == t for r in hum)} | {len(hr)} | {c.get('RENDERED', 0)} | {c.get('RENDERED_PARTIAL_MISSING_BOBS', 0)} | {c.get('VARIANT_INCOMPATIBLE', 0)} | {c.get('NO_DIRECT_FRAMES', 0)} |")
w('\n## Vehicles by tribe\n\n| Tribe | Graphics-bound types | Native declaration without graphics |\n|---|---|---|')
for t in sorted({r['TRIBE_ID'] for r in veh}):
    vb = [r['NATIVE_NAME'] + f" (type {r['TYPE_ID']})" for r in veh if r['TRIBE_ID'] == t and r['NATIVE_DECLARATION'] == 'GRAPHICS_BOUND']
    vn = [r['NATIVE_NAME'] + f" (type {r['TYPE_ID']})" for r in veh if r['TRIBE_ID'] == t and r['NATIVE_DECLARATION'] != 'GRAPHICS_BOUND']
    w(f"| {TN.get(t, t)} | {', '.join(vb) or '-'} | {', '.join(vn) or '-'} |")
w('\n## Other categories\n\n| Category | Count |\n|---|---|')
for k, v in [('Goods', sum(1 for r in X if r['CATEGORY'] == 'Goods')), ('Goods with world pile / UI visual', sum(1 for r in X if r['CATEGORY'] == 'Goods' and r['THUMB'])),
             ('Animal life stages with graphics', sum(1 for r in ani if r.get('NATIVE_DECLARATION') != 'NATIVE_DECLARATION_NO_GRAPHICS')),
             ('Animal tribes/stages declared without graphics', sum(1 for r in ani if r.get('NATIVE_DECLARATION') == 'NATIVE_DECLARATION_NO_GRAPHICS')),
             ('Animal animation rows', sum(1 for r in X if r['CATEGORY'] == 'Animal animation')),
             ('Landscape definitions', sum(1 for r in X if r['CATEGORY'] == 'Landscapes')), ('Terrain patterns', sum(1 for r in X if r['SUBCATEGORY'] == 'Pattern')),
             ('Terrain transitions', sum(1 for r in X if r['SUBCATEGORY'] == 'Transition')), ('UI sprites', len(ui)),
             ('UI sprites with native palette evidence', sum(r['STATUS'] == 'PALETTE_EVIDENCED' for r in ui)), ('Effects catalogue rows', len(fx)),
             ('Shadow records', sum(1 for r in X if r['CATEGORY'] == 'Shadows')), ('Construction sets', sum(1 for r in X if r['CATEGORY'] == 'Construction'))]:
    w(f'| {k} | {v} |')
w('\n## Status counts (master cross-reference, one row per catalogued asset)\n\n| Status | Rows |\n|---|---|')
for s in ('SOURCE_COMPLETE', 'PIXEL_CONFIRMED', 'MANUAL_CONFIRMED_1TO1', 'PARTIAL', 'PRESENTATION_PARTIAL', 'PRESENTATION_APPROXIMATION', 'UNKNOWN'):
    w(f'| {s} | {st.get(s, 0)} |')
w(f"\nPixel validation: {cat['pixelValidation']['framesConfirmed']} frame/image comparisons against production code, {cat['pixelValidation']['mismatch']} mismatches.\n")
w('## Remaining UNKNOWN items by reason\n\n| Class | Sub-reason | Items |\n|---|---|---|')
uc = collections.Counter((r['UNKNOWN_CLASS'], r['REASON'] if r['UNKNOWN_CLASS'] in ('UNKNOWN_NAMED_SEQUENCE', 'UNKNOWN_UNREFERENCED') else '') for r in unk)
for (c, r_), n in sorted(uc.items()):
    w(f'| {c} | {r_} | {n} |')
w('''
Reason definitions (native evidence):
- SHADOWED_DUPLICATE_RECORD: animations.cif authors several records with the same (tribe, job, selector, sub-id/walk-speed) key; loader 0x0048BD66 keeps authored order and lookup 0x0048D027 returns the first, so later records are unreachable.
- HEAD_SEQUENCE_OVERRIDE: head-library frames at body-sequence numbering; the record's gfxbobseqhead selects another base (0x00494AE6), e.g. human_man_hunter_walk heads use human_man_generic_walk.
- SEQUENCE_USED_WITH_OTHER_LIBRARIES_ONLY: sequence (global first-match numbering, 0x0048CEA1) is used only by owners bound to other libraries/tribes.
- SEQUENCE_BOUND_OFFSET_UNUSED: sequence is used with this library, but the frame offset is in no native direction list.
- SEQUENCE_NEVER_REFERENCED: named BobSeq with no GfxAnimAtomic/GfxWalkAtomic reference.
- UNKNOWN_UNSUPPORTED_PIXEL_KIND: test_house.bmd kind-3 descriptors; none of the native scanline walkers (0x00439AB3, 0x00463AEE..0x0049E618) handle kind 3, so no decoder support was added.
- UNKNOWN_NATIVE_STUB: native definitions referencing frames absent from their declared library (e.g. door BOB 66 in Frank/Byzantine/Pyramid houses, BOB 2000/4000 landscape stubs, truncated soldier walk_meat sequences).
- UNKNOWN_GRAPHICS_BINDING: native vehicle/animal declarations with no jobgraphics binding (e.g. Ship Big, ibex, dromedary, elephant, horse).
- UNKNOWN_PALETTE: GUI sprites without native draw-call palette evidence (index data exported, no palette guessed).
''')
w('## Browser and validation\n\n| Check | Result |\n|---|---|')
for k, v in [('HTML pages', val['htmlPages']), ('HTML links checked', val['htmlLinksChecked']), ('Data paths checked', val['dataPathsChecked']),
             ('BROKEN LINKS', val['brokenLinks']), ('CATALOGUED WITHOUT BROWSER LINK', val['cataloguedWithoutBrowserRoute']),
             ('Mojibake files', val['mojibakeFiles']), ('Non-UTF-8 generated text files', len(val['nonUtf8TextFiles'])), ('HTML without UTF-8 meta', len(val['htmlWithoutUtf8Meta']))]:
    w(f'| {k} | {v} |')
w('\n## Focused tests\n\n| Test | Result |\n|---|---|')
for t in tests:
    w(f"| {t['test']} | {t['result']} |")
w('| C++ ctest focused set (16): bob_compositor, cif_byte_transform, cif_document_runtime, cif_cstring_array, mounted_library_file, production_resource_store, '
  'gfxhouse_registry_layout, gfxhouse_door_offset_initialization, directdraw_log_palette, gfx_landscape_registry, pattern_transition_registry, font_text_rendering, '
  'font_glyph_advance_regression, world_human_sprite_runtime, world_animal_vehicle_sprite_runtime, human_graphics_save | 16/16 PASS (no production source changed) |')
w(f"\n## Source hash check\n\nFiles checked: {hashes.get('filesChecked', 'pending')}; changed: {len(hashes.get('changed', [])) if hashes else 'pending'}.\n\n"
  f"**ORIGINAL FILES MODIFIED: {hashes.get('ORIGINAL_FILES_MODIFIED', 'PENDING')}**\n")
(ROOT / 'ASSET_LIBRARY_REPORT.md').write_text('\n'.join(L), encoding='utf-8')
print('\n'.join(L))
